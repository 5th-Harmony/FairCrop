@router.get("/{lang_code}")
async def get_language_dictionary(lang_code: str, db: AsyncSession = Depends(get_db)):
    """
    Get full localized translation dictionary for a given language code.
    Sources from database or built-in comprehensive language pack.
    """
    code = lang_code.lower().strip()
    
    # 1. Check if translations exist in DB
    query = select(Translation).where(Translation.lang_code == code)
    result = await db.execute(query)
    db_rows = result.scalars().all()
    
    if db_rows:
        dict_resp = {row.key: row.translation for row in db_rows}
        # Merge with base English for any missing keys
        merged = dict(TRANSLATION_DICTS.get("en", {}))
        merged.update(dict_resp)
        return {
            "lang_code": code,
            "total_keys": len(merged),
            "translations": merged
        }

    # 2. Check built-in dictionaries
    if code in TRANSLATION_DICTS:
        merged = dict(TRANSLATION_DICTS.get("en", {}))
        merged.update(TRANSLATION_DICTS[code])
        return {
            "lang_code": code,
            "total_keys": len(merged),
            "translations": merged
        }

    # 3. Fallback to Hindi or English with script indication
    fallback_dict = dict(TRANSLATION_DICTS.get("hi", TRANSLATION_DICTS["en"]))
    return {
        "lang_code": code,
        "is_fallback": True,
        "total_keys": len(fallback_dict),
        "translations": fallback_dict
    }


@router.post("/seed")
async def seed_translations_to_database(db: AsyncSession = Depends(get_db)):
    """Seed all 22 languages and dictionaries into database tables."""
    inserted = 0
    for lang_code, trans_map in TRANSLATION_DICTS.items():
        for key, text in trans_map.items():
            # Check existing
            q = select(Translation).where(
                (Translation.lang_code == lang_code) & (Translation.key == key)
            )
            res = await db.execute(q)
            existing = res.scalars().first()
            if not existing:
                t = Translation(
                    lang_code=lang_code,
                    key=key,
                    translation=text,
                    category="ui"
                )
                db.add(t)
                inserted += 1

    await db.commit()
    return {"status": "success", "inserted_count": inserted}
